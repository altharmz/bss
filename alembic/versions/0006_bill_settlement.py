BOUNDS_FUNCTION = """
CREATE FUNCTION bill_allocation_bounds() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    bill_due numeric;
    total numeric;
BEGIN
    SELECT amount_due INTO bill_due FROM customer_bill WHERE id = NEW.customer_bill_id;
    IF bill_due <= 0 THEN
        RAISE EXCEPTION 'bill % has amount due %: nothing to pay', NEW.customer_bill_id, bill_due
            USING ERRCODE = 'check_violation';
    END IF;
    SELECT sum(amount) INTO total FROM bill_allocation
        WHERE customer_bill_id = NEW.customer_bill_id;
    IF total > bill_due THEN
        RAISE EXCEPTION 'bill % over-allocated: % > %', NEW.customer_bill_id, total, bill_due
            USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.payment_id IS NOT NULL THEN
        SELECT sum(a.amount) INTO total FROM bill_allocation a WHERE a.payment_id = NEW.payment_id;
        IF total > (SELECT amount FROM payment WHERE id = NEW.payment_id) THEN
            RAISE EXCEPTION 'payment % over-allocated: %', NEW.payment_id, total
                USING ERRCODE = 'check_violation';
        END IF;
    ELSE
        SELECT amount_due INTO bill_due FROM customer_bill WHERE id = NEW.credit_bill_id;
        IF bill_due >= 0 THEN
            RAISE EXCEPTION 'bill % has amount due %: not a credit note',
                NEW.credit_bill_id, bill_due USING ERRCODE = 'check_violation';
        END IF;
        SELECT sum(a.amount) INTO total FROM bill_allocation a
            WHERE a.credit_bill_id = NEW.credit_bill_id;
        IF total > -bill_due THEN
            RAISE EXCEPTION 'credit note % over-allocated: % > %', NEW.credit_bill_id, total,
                -bill_due USING ERRCODE = 'check_violation';
        END IF;
    END IF;
    RETURN NULL;
END;
$$
"""


