"""SIM and eSIM inventory on the IMSI resource, batches and the swap_sim command (issue #186).

Revision ID: 0054
Revises: 0053
"""

from alembic import op

revision = "0054"
down_revision = "0053"
branch_labels = None
depends_on = None


BACKFILL = """
UPDATE subscriber_number n SET
    sim_state = CASE
        WHEN EXISTS (SELECT 1 FROM number_assignment a
            WHERE a.subscriber_number_id = n.id AND a.cancelled_at IS NULL
            AND NOT isempty(a.valid_for) AND upper_inf(a.valid_for)) THEN 'active'
        WHEN n.administrative_state = 'locked' AND EXISTS (SELECT 1 FROM number_assignment a
            WHERE a.subscriber_number_id = n.id AND a.cancelled_at IS NULL) THEN 'retired'
        ELSE 'in_stock' END,
    sim_product_id = (SELECT a.product_id FROM number_assignment a
        WHERE a.subscriber_number_id = n.id AND a.cancelled_at IS NULL
        AND NOT isempty(a.valid_for) AND upper_inf(a.valid_for) LIMIT 1)
WHERE n.resource_specification_id = 'imsi';
"""


def upgrade() -> None:
    op.execute("""
        CREATE TABLE sim_batch (
            name text PRIMARY KEY CHECK (name ~ '^[A-Za-z0-9._-]{1,60}$'),
            sim_type text NOT NULL CHECK (sim_type IN ('physical', 'esim')),
            source text NOT NULL CHECK (source IN ('import', 'generated')),
            created_at timestamptz NOT NULL
        );
        COMMENT ON TABLE sim_batch IS
            'A stocked batch of SIMs or eSIM profiles (one type per batch), imported or generated by the network adapter.';

        ALTER TABLE subscriber_number
            ADD COLUMN sim_type text CHECK (sim_type IN ('physical', 'esim')),
            ADD COLUMN sim_state text NOT NULL DEFAULT 'in_stock'
                CHECK (sim_state IN ('in_stock', 'reserved', 'active', 'retired')),
            ADD COLUMN sim_product_id uuid REFERENCES product(id),
            ADD COLUMN sim_batch text REFERENCES sim_batch(name),
            ADD COLUMN esim_smdp_address text,
            ADD COLUMN esim_matching_id text,
            ADD CONSTRAINT subscriber_number_sim_kind_check CHECK (
                (sim_type IS NULL AND sim_batch IS NULL)
                OR resource_specification_id = 'imsi'),
            ADD CONSTRAINT subscriber_number_sim_iccid_check CHECK (
                sim_type IS NULL OR iccid IS NOT NULL),
            ADD CONSTRAINT subscriber_number_esim_check CHECK (
                (sim_type = 'esim' AND esim_smdp_address IS NOT NULL
                    AND esim_matching_id IS NOT NULL)
                OR (sim_type IS DISTINCT FROM 'esim' AND esim_smdp_address IS NULL
                    AND esim_matching_id IS NULL)),
            ADD CONSTRAINT subscriber_number_sim_holder_check CHECK (
                sim_state NOT IN ('reserved', 'active') OR sim_product_id IS NOT NULL);
        CREATE UNIQUE INDEX subscriber_number_sim_active_key ON subscriber_number (sim_product_id)
            WHERE sim_state = 'active';
        CREATE UNIQUE INDEX subscriber_number_sim_reserved_key ON subscriber_number (sim_product_id)
            WHERE sim_state = 'reserved';
        CREATE INDEX subscriber_number_sim_stock_idx ON subscriber_number
            (sim_type, created_at, value) WHERE sim_state = 'in_stock'
            AND resource_specification_id = 'imsi';

    """ + BACKFILL + """

        ALTER TABLE network_command
            DROP CONSTRAINT network_command_kind_check,
            ADD CONSTRAINT network_command_kind_check CHECK (kind IN
                ('activate', 'suspend', 'restore', 'deactivate', 'change_profile', 'swap_sim'));
        COMMENT ON COLUMN network_command.kind IS
            'activate (add), suspend, restore (resume), deactivate (terminate), change_profile (offering change), swap_sim (the line moves to another SIM or eSIM).';

        COMMENT ON COLUMN subscriber_number.sim_type IS
            'imsi resources only: physical SIM or eSIM profile; null for an IMSI resource created through the plain TMF639 POST (a LogicalResource without a batch).';
        COMMENT ON COLUMN subscriber_number.sim_state IS
            'imsi resources only (msisdn rows keep the default, unused): in_stock, reserved (claimed, the network has not confirmed activation or swap), active, retired.';
        COMMENT ON COLUMN subscriber_number.sim_product_id IS
            'The line (product) holding the SIM while reserved or active (kept as history once retired); a SIM is active on at most one line.';
        COMMENT ON COLUMN subscriber_number.sim_batch IS 'The stocked batch the SIM came in.';
        COMMENT ON COLUMN subscriber_number.esim_smdp_address IS
            'eSIM profile: the SM-DP+ address of its activation code. Ki and OPc are never stored.';
        COMMENT ON COLUMN subscriber_number.esim_matching_id IS
            'eSIM profile: the matching ID of its activation code; a secret, shown only while the profile is reserved or active.';
    """)


def downgrade() -> None:
    op.execute("""
        DO $$ BEGIN
            IF EXISTS (SELECT 1 FROM network_command WHERE kind = 'swap_sim') THEN
                RAISE EXCEPTION 'swap_sim commands must be removed before downgrade';
            END IF;
        END $$;
        ALTER TABLE network_command
            DROP CONSTRAINT network_command_kind_check,
            ADD CONSTRAINT network_command_kind_check CHECK (kind IN
                ('activate', 'suspend', 'restore', 'deactivate', 'change_profile'));
        COMMENT ON COLUMN network_command.kind IS
            'activate (add), suspend, restore (resume), deactivate (terminate), offering change -> change_profile.';
        DROP INDEX subscriber_number_sim_stock_idx;
        DROP INDEX subscriber_number_sim_reserved_key;
        DROP INDEX subscriber_number_sim_active_key;
        ALTER TABLE subscriber_number
            DROP CONSTRAINT subscriber_number_sim_holder_check,
            DROP CONSTRAINT subscriber_number_esim_check,
            DROP CONSTRAINT subscriber_number_sim_iccid_check,
            DROP CONSTRAINT subscriber_number_sim_kind_check,
            DROP COLUMN esim_matching_id,
            DROP COLUMN esim_smdp_address,
            DROP COLUMN sim_batch,
            DROP COLUMN sim_product_id,
            DROP COLUMN sim_state,
            DROP COLUMN sim_type;
        DROP TABLE sim_batch;
    """)
