def render_api_index(pages: dict[str, list[dict]], data: dict) -> str:
    specs = {spec["key"]: spec for spec in data["specs"]}
    lines = [HEADER, "# API reference\n"]
    lines.append(
        "One page per API, generated from `app.openapi()` (what the app really serves) and"
        " cross-checked against the vendored specs in `spec/`: the generator fails if an"
        " operation has no matching method and path in its spec (service endpoints"
        " excepted, listed on [service.md](service.md)).\n"
    )
    lines.append("| API | Version | Base path | Operations | Spec |")
    lines.append("|---|---|---|---|---|")
    total = 0
    for api in APIS:
        ops = pages.get(api.page, [])
        total += len(ops)
        spec = specs.get(api.spec) if api.spec else None
        spec_link = f"[`{spec['file']}`](../../{spec['file']})" if spec else "-"
        base = code(api.base) if api.base else "-"
        lines.append(
            f"| [{api.title}]({api.page}.md) | {api.version} | {base} | {len(ops)} | {spec_link} |"
        )
    lines.append(f"\n{total} operations in total.\n")
    notes = NOTES / "README.md"
    if notes.exists():
        lines.append(notes.read_text().strip() + "\n")
    return "\n".join(lines).rstrip() + "\n"


