MERMAID_TYPES = [
    ("timestamp with time zone", "timestamptz"),
    ("character varying", "varchar"),
    ("character", "char"),
]


def mermaid_type(pg_type: str) -> str:
    for long, short in MERMAID_TYPES:
        if pg_type.startswith(long):
            pg_type = short + pg_type[len(long) :]
    return re.sub(r"[^A-Za-z0-9_]", "", pg_type.split("(")[0]) or "type"


def foreign_keys(table: dict) -> list[tuple[list[str], str, list[str], str]]:
    """(columns, referenced table, referenced columns, name) per FK."""
    out = []
    for con in table["constraints"]:
        if con["kind"] != "f":
            continue
        m = re.match(r"FOREIGN KEY \(([^)]*)\) REFERENCES (\w+)(?:\(([^)]*)\))?", con["definition"])
        if not m:
            raise Failure(f"cannot parse foreign key {con['name']}: {con['definition']}")
        cols = [c.strip() for c in m.group(1).split(",")]
        ref_cols = [c.strip() for c in (m.group(3) or "id").split(",")]
        out.append((cols, m.group(2), ref_cols, con["name"]))
    return out


def area_of(table: str) -> str:
    for area, tables in AREAS.items():
        if table in tables:
            return area
    raise Failure(f"table {table} has no area in AREAS")


def check_tables(tables: dict[str, dict]) -> list[str]:
    problems = []
    listed = {t for ts in AREAS.values() for t in ts}
    for name, table in tables.items():
        if name not in listed:
            problems.append(f"table {name}: no area in AREAS")
        if not table["comment"]:
            problems.append(f"table {name}: no COMMENT (add one in a migration)")
    for name in sorted(listed - set(tables)):
        problems.append(f"AREAS names {name}, which does not exist at head")
    return problems


