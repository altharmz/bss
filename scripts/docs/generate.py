def api_of(path: str) -> Api | None:
    best = None
    for api in APIS:
        if api.base and (path == api.base or path.startswith(api.base + "/")):
            if best is None or len(api.base) > len(best.base):
                best = api
    return best


def handler_of(path: str) -> str:
    best = ""
    for prefix in HANDLERS:
        if (path == prefix or path.startswith(prefix.rstrip("/") + "/")) and len(prefix) > len(
            best
        ):
            best = prefix
    return HANDLERS.get(best, "?")


def match_operations(data: dict) -> tuple[dict[str, list[dict]], list[str]]:
    """Every app operation assigned to a page, with its spec operation (or a NO_SPEC
    reason). Returns (page -> operations, problems)."""
    specs = {spec["key"]: spec for spec in data["specs"]}
    pages: dict[str, list[dict]] = defaultdict(list)
    problems = []
    for op in data["operations"]:
        key = (op["method"], op["path"])
        entry = dict(op)
        entry["handler"] = handler_of(op["path"])
        if key in NO_SPEC:
            page, why = NO_SPEC[key]
            entry["spec_op"] = None
            entry["no_spec"] = why
            pages[page].append(entry)
            continue
        api = api_of(op["path"])
        if api is None or api.spec is None:
            problems.append(f"{op['method']} {op['path']}: belongs to no API page")
            continue
        relative = norm(op["path"][len(api.base) :])
        found = [
            s
            for s in specs[api.spec]["operations"]
            if s["method"] == op["method"] and norm(s["path"]) == relative
        ]
        if not found:
            spec_file = specs[api.spec]["file"]
            problems.append(
                f"{op['method']} {op['path']}: no {op['method']} {relative} in {spec_file}"
            )
            continue
        entry["spec_op"] = found[0]
        entry["no_spec"] = None
        pages[api.page].append(entry)
    return pages, problems


def resources_of(ops: list[dict], api: Api) -> list[str]:
    seen = []
    for op in ops:
        if op["spec_op"] is None:
            continue
        first = norm(op["spec_op"]["path"]).split("/")[1]
        if first not in seen:
            seen.append(first)
    return seen


def params_text(op: dict, filters: dict[str, list[str]]) -> str:
    parts = []
    path_params = [p["name"] for p in op["params"] if p["in"] == "path"]
    if path_params:
        parts.append("path: " + ", ".join(code(p) for p in path_params))
    spec_op = op["spec_op"]
    if op["path"].startswith("/tmf-api/") and spec_op is not None:
        if op["method"] == "GET" and "{" not in op["path"]:
            parts.append("query: `offset`, `limit` (max 100), `fields`")
            listed = filters.get(op["path"], [])
            parts.append(
                "filters (equality): " + (", ".join(code(f) for f in listed) if listed else "none")
            )
        elif op["method"] in ("GET", "POST", "PATCH"):
            parts.append("query: `fields`")
    elif spec_op is not None:
        query = [p for p in spec_op["params"] if p["in"] == "query"]
        if query:
            parts.append(
                "query: "
                + ", ".join(
                    code(p["name"]) + (" (required)" if p["required"] else "") for p in query
                )
            )
    if op["method"] in ("POST", "PATCH") and op["path"].startswith(("/tmf-api/", "/internal/")):
        media = "application/merge-patch+json" if op["method"] == "PATCH" else "application/json"
        if op["path"].startswith("/internal/v1/users"):
            media = "application/json"
        parts.append(f"body: {code(media)}")
    return "; ".join(parts) or "-"


def schemas_text(op: dict, spec_file: str | None) -> tuple[str, str]:
    spec_op = op["spec_op"]
    if spec_op is None:
        return "-", "-"
    request = code(spec_op["request"]) if spec_op["request"] else "-"
    success = [
        f"{status} {code(schema) if schema else '(no body)'}"
        for status, schema in sorted(spec_op["responses"].items())
        # a 2xx without a body (the TMF specs' asynchronous 202) is never answered here,
        # except 204 on a DELETE (TMF620 catalog deletes, tests/apiclient.py checks it)
        if status.startswith("2") and (schema or status == "204")
    ]
    return request, ", ".join(success) or "-"


def spec_status_text(api: Api, ops: list[dict], spec: dict | None) -> list[str]:
    """What the spec declares for the implemented resources but we do not expose, and
    which resources of the spec are not implemented at all."""
    if spec is None:
        return []
    implemented = {
        (op["spec_op"]["method"], norm(op["spec_op"]["path"])) for op in ops if op["spec_op"]
    }
    resources = resources_of(ops, api)
    missing_ops = []
    other_resources = []
    for s in spec["operations"]:
        first = norm(s["path"]).split("/")[1]
        key = (s["method"], norm(s["path"]))
        if key in implemented:
            continue
        if first in resources:
            missing_ops.append(f"`{s['method']} {s['path']}`")
        elif first not in other_resources:
            other_resources.append(first)
    lines = []
    if missing_ops:
        lines.append(
            "- Declared by the spec for the implemented resources but **not exposed** (an"
            " unsupported method on an exposed path answers 405; an unknown path 404): "
            + ", ".join(missing_ops)
            + "."
        )
    if other_resources:
        lines.append(
            "- Resources of the spec that are **not implemented**: "
            + ", ".join(f"`/{r}`" for r in other_resources)
            + " (`/listener/*` is the client's side: hubs subscribe, this service sends)."
        )
    return lines


